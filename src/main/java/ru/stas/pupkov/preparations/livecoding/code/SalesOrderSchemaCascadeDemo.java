package ru.stas.pupkov.preparations.livecoding.code;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * Схема sales_order / sales_order_line: ON DELETE CASCADE + выборка заказов по item_no.
 */
public class SalesOrderSchemaCascadeDemo {

    public static void main(String[] args) throws Exception {
        try (Connection c = DriverManager.getConnection("jdbc:h2:mem:sales;MODE=PostgreSQL")) {
            try (Statement st = c.createStatement()) {
                st.execute("""
                        create table sales_order(
                          id bigint generated by default as identity primary key,
                          description varchar(25) not null,
                          integration_id int not null unique
                        )
                        """);
                st.execute("""
                        create table sales_order_line(
                          id bigint generated by default as identity primary key,
                          order_id bigint not null references sales_order(id) on delete cascade,
                          item_no varchar(20),
                          quantity int not null default 1,
                          amount decimal(19,2) not null default 0
                        )
                        """);
            }

            long orderId;
            try (PreparedStatement ps = c.prepareStatement(
                    "insert into sales_order(description, integration_id) values (?, ?)",
                    Statement.RETURN_GENERATED_KEYS)) {
                ps.setString(1, "Demo order");
                ps.setInt(2, 1001);
                ps.executeUpdate();
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    keys.next();
                    orderId = keys.getLong(1);
                }
            }

            insertLine(c, orderId, "SKU-1", 2, "10.50");
            insertLine(c, orderId, "SKU-2", 1, "3.00");

            System.out.println("orders with SKU-1: " + findOrderIdsByItem(c, "SKU-1"));
            System.out.println("lines before delete: " + countLines(c));

            try (PreparedStatement ps = c.prepareStatement("delete from sales_order where id = ?")) {
                ps.setLong(1, orderId);
                ps.executeUpdate();
            }

            System.out.println("lines after delete order: " + countLines(c) + " (ожидаем 0 — CASCADE)");
        }
    }

    private static void insertLine(Connection c, long orderId, String item, int qty, String amount)
            throws Exception {
        try (PreparedStatement ps = c.prepareStatement(
                "insert into sales_order_line(order_id, item_no, quantity, amount) values (?,?,?,?)")) {
            ps.setLong(1, orderId);
            ps.setString(2, item);
            ps.setInt(3, qty);
            ps.setBigDecimal(4, new BigDecimal(amount));
            ps.executeUpdate();
        }
    }

    private static List<Long> findOrderIdsByItem(Connection c, String itemNo) throws Exception {
        List<Long> ids = new ArrayList<>();
        try (PreparedStatement ps = c.prepareStatement("""
                select distinct o.id
                from sales_order o
                join sales_order_line l on l.order_id = o.id
                where l.item_no = ?
                """)) {
            ps.setString(1, itemNo);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    ids.add(rs.getLong(1));
                }
            }
        }
        return ids;
    }

    private static int countLines(Connection c) throws Exception {
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("select count(*) from sales_order_line")) {
            rs.next();
            return rs.getInt(1);
        }
    }
}
